"""CPA 0.8.8 save fix; leaves all locked source files unchanged.
Run from CausFlow_CPA_Fig2 with the causflow_baselines Python executable.
--mode probe performs the same small source-only training subset as the original
smoke, then saves actual weights and checks that scvi's file contains them.
--mode run delegates to the original locked adapter; only CPA.save is wrapped.
"""
import argparse
import hashlib
import importlib.metadata as md
import importlib.util
import json
from pathlib import Path
import sys
import tempfile


def install_save_guard(CPA):
    original = CPA.save

    def guarded(self, dir_path, overwrite=False, save_anndata=False, **kwargs):
        path = Path(dir_path)
        if path.exists():
            raise FileExistsError(f'Refusing to overwrite existing model directory: {path}')
        # CPA itself creates dir_path before calling scvi BaseModelClass.save.
        result = original(self, str(path), overwrite=True,
                          save_anndata=save_anndata, **kwargs)
        weights = path / 'model.pt'
        if not weights.is_file() or weights.stat().st_size == 0:
            raise RuntimeError(f'Expected actual model weights: {weights}')
        print('CPA WEIGHTS SAVED:', weights, weights.stat().st_size, 'bytes', flush=True)
        return result

    CPA.save = guarded


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--mode', choices=['probe', 'run'], required=True)
    parser.add_argument('--root', default='.')
    parser.add_argument('--seeds', nargs='+', type=int, default=[0])
    a = parser.parse_args()
    root = Path(a.root).resolve()
    out = root / 'Output/TrainingSufficiency_v2'
    runner = root / 'CausFlow_TrainingSufficiency/run_professional.py'
    lock = json.loads((out / 'lock.json').read_text(encoding='utf8'))
    if hashlib.sha256(runner.read_bytes()).hexdigest() != lock['source_hashes']['run_professional.py']:
        raise RuntimeError('Original adapter hash changed; stop')
    if md.version('cpa-tools') != '0.8.8' or md.version('scvi-tools') != '0.20.3':
        raise RuntimeError('Expected verified CPA 0.8.8 / scvi-tools 0.20.3 environment')
    import cpa
    import torch
    import numpy as np
    if not torch.cuda.is_available():
        raise RuntimeError('CUDA not available')
    install_save_guard(cpa.CPA)
    spec = importlib.util.spec_from_file_location('locked_professional', runner)
    r = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(r)
    repair_sha = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    print('CPA SAVE HOTFIX SHA256:', repair_sha, flush=True)
    if a.mode == 'probe':
        from types import SimpleNamespace
        d, m, l, fit, q, genes = r.load(SimpleNamespace(out=out))
        r.reset(0)
        row = q.iloc[0]
        x, ix = r.source(d, m, fit, row)
        rng = np.random.default_rng(0)
        mask = (fit.obs.drug == row.drug) & (fit.obs.cell_line == row.cell_line)
        chosen = np.unique(np.concatenate([ix, np.flatnonzero(mask), rng.choice(fit.n_obs, min(1000, fit.n_obs), replace=False)]))
        work = fit[chosen].copy()
        base = out / 'continuation/save_probes'
        base.mkdir(parents=True, exist_ok=True)
        dest = Path(tempfile.mkdtemp(prefix='CPA_', dir=base))
        model = r.fit_cpa(cpa.CPA, work, m, 0, True, 1, dest, True)
        model.save(str(dest / 'model'), overwrite=False, save_anndata=False)
        # Only deserialize the trusted weights just generated by this process.
        checkpoint = torch.load(dest / 'model/model.pt', map_location='cpu')
        if not isinstance(checkpoint, dict) or not checkpoint.get('model_state_dict'):
            raise RuntimeError('Missing model_state_dict in save file')
        # Confirm finite predictions from trained model, same original decoder path.
        y, mu, v = r.cpa_predict(model, x, row.drug.replace('+', '__PLUS__'), float(row.dose), row.cell_line, int(row.query_id[1:]))
        for arr in (y, mu, v):
            if arr.shape != (m['n_pred'], len(genes)) or not np.isfinite(arr).all():
                raise RuntimeError('Invalid prediction in save probe')
        receipt = {'repair_sha256': repair_sha, 'lock_sha256': r.digest(out/'lock.json'), 'export_manifest_sha256': r.digest(d/'manifest.json'), 'weights_sha256': r.digest(dest/'model/model.pt'), 'probe_path': str(dest), 'versions': r.versions(), 'scope': 'small real-data train/save/read/predict; not a formal result'}
        r.dump(base/'receipt.json', receipt)
        print('CPA SAVE PROBE PASS', dest, flush=True)
        return
    receipt = json.loads((out/'continuation/save_probes/receipt.json').read_text(encoding='utf8'))
    if any(receipt[k] != v for k, v in {'repair_sha256': repair_sha, 'lock_sha256': r.digest(out/'lock.json'), 'export_manifest_sha256': r.digest(out/'external_input/manifest.json'), 'versions': r.versions()}.items()):
        raise RuntimeError('Probe does not match current code, protocol or environment')
    # Keep all original conditions, hyperparameters, early stopping and predictions.
    for seed in a.seeds:
        for path in [out/'professional_models/CPA'/f'seed_{seed}', out/'predictions/CPA'/f'seed_{seed}', out/'predictions/CPA_mean'/f'seed_{seed}']:
            if path.exists():
                raise FileExistsError(f'Preserve existing attempt before running: {path}')
    sys.argv = [str(runner), '--mode', 'run', '--out', str(out), '--model', 'CPA', '--device', 'cuda', '--seeds', *map(str,a.seeds)]
    r.main()
    for seed in a.seeds:
        r.dump(out/'professional_models/CPA'/f'seed_{seed}'/'save_hotfix.json', receipt)


if __name__ == '__main__':
    main()
